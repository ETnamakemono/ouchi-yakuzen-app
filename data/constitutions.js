export const CONST_MAP = Object.fromEntries(CONSTITUTIONS.map(c => [c.id, c]));

// 判定：各体質の平均点（0〜4）。2.0以上を「傾向あり」。最高点を主体質。すべて2.0未満なら平和質。
export function judgeConstitution(answers) {
  const scores = {};
  for (const c of CONSTITUTIONS) {
    if (!c.questions.length) continue;
    const vals = c.questions.map((_, i) => answers[`${c.id}_${i}`] ?? 0);
    scores[c.id] = vals.reduce((a, b) => a + b, 0) / vals.length;
  }
  const tendencies = Object.entries(scores).filter(([, s]) => s >= 2).sort((a, b) => b[1] - a[1]).map(([id]) => id);
  return { main: tendencies[0] || 'heiwa', tendencies, scores };
}
